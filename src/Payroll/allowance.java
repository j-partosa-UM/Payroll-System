    private void button_calculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button_calculateActionPerformed
        // TODO add your handling code here:

        double salary = Double.parseDouble(txt_salary.getText());
        double overtime = Double.parseDouble(txt_overtime.getText());

        double eight = 8;
        double overtimeRate = 1.5;
        
        //calculate the total hours of overtime
        double Total_Overtime = overtime * overtimeRate;
        String x = String.valueOf(Total_Overtime);
        txt_totalovertime.setText(x);

        //calculate overall overtime 
        double dbop = salary/eight;
        String s = String.valueOf(dbop);
        txt_rate.setText(s);
        
        double med = Double.parseDouble(txt_med.getText());
        double bonus = Double.parseDouble(txt_bonus.getText());
        double other = Double.parseDouble(txt_other.getText());
        double f = med+bonus+other;
        double calc = Total_Overtime * dbop + f;
        String t = String.valueOf(calc);
        label_total.setText(t);
        
    }//GEN-LAST:event_button_calculateActionPerformed

