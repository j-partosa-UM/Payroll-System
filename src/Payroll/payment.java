    private void button_generateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button_generateActionPerformed
        // TODO add your handling code here:

        String value = txt_surname.getText();
        String value0 = txt_firstname.getText();
        String value1 = txt_id.getText();
        String value2 = txt_dept.getText();
        String value3 = txt_designation.getText();
        String value4 = txt_basicsalary.getText();
        String value5 = txt_allowance.getText();
        String value6 = txt_deduction.getText();

        JFileChooser dialog = new JFileChooser();
        dialog.setSelectedFile(new File(value +" "+ value0+"-PaySlip"+".pdf"));
        int dialogResult = dialog.showSaveDialog(null);
        if (dialogResult==JFileChooser.APPROVE_OPTION){
            String filePath = dialog.getSelectedFile().getPath();

            try {
                // TODO add your handling code here:

                String sql ="select * from Deductions where Id = '"+value1+"'";
                pst=conn.prepareStatement(sql);
                rs=pst.executeQuery();
                String reason = rs.getString(5);
                
                
                String sq ="select * from Allowance where Id = '"+value1+"'";
                pst1=conn.prepareStatement(sq);
                rs1=pst1.executeQuery();
               

                double calcTotal = Double.parseDouble(value4);
                double x = Double.parseDouble(value5);
                double v = Double.parseDouble(value6);
                double total = calcTotal+ x -v;

                Document myDocument = new Document();
                PdfWriter myWriter = PdfWriter.getInstance(myDocument, new FileOutputStream(filePath));
                myDocument.open();

                myDocument.add(new Paragraph("PAY SLIP",FontFactory.getFont(FontFactory.TIMES_BOLD,12,Font.BOLD )));
                myDocument.add(new Paragraph(new Date().toString()));
                myDocument.add(new Paragraph("-------------------------------------------------------------------------------------------"));
                myDocument.add((new Paragraph("EMPLOYEE DETAILS",FontFactory.getFont(FontFactory.TIMES_ROMAN,10,Font.BOLD))));
                myDocument.add((new Paragraph("Name: " +value+ ", "+value0,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL))));
                myDocument.add((new Paragraph("Designation: "+value3,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL))));
                myDocument.add((new Paragraph("Department: "+value2,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL))));
                myDocument.add(new Paragraph("-------------------------------------------------------------------------------------------"));
                myDocument.add(new Paragraph("SALARY",FontFactory.getFont(FontFactory.TIMES_ROMAN,10,Font.BOLD)));
                myDocument.add(new Paragraph("Basic Salary: $"+calcTotal,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("Overtime: "+rs1.getString(2)+" Hours",FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("Medical: $" +rs1.getString(3),FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("Bonus: $"+rs1.getString(4),FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("Other: $"+rs1.getString(5),FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("-------------------------------------------------------------------------------------------"));
                myDocument.add(new Paragraph("DEDUCTION",FontFactory.getFont(FontFactory.TIMES_ROMAN,10,Font.BOLD)));
                myDocument.add(new Paragraph("Deduction Details: "+reason,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("Total Deductions : $"+value6 ,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("-------------------------------------------------------------------------------------------"));
                myDocument.add(new Paragraph("TOTAL PAYMENT",FontFactory.getFont(FontFactory.TIMES_ROMAN,10,Font.BOLD)));
                myDocument.add(new Paragraph("Net Pay : " +total,FontFactory.getFont(FontFactory.TIMES_ROMAN,8,Font.NORMAL)));
                myDocument.add(new Paragraph("-------------------------------------------------------------------------------------------"));

                myDocument.newPage();
                myDocument.close();
                JOptionPane.showMessageDialog(null,"Report was successfully generated");

            }
            catch(DocumentException | HeadlessException | FileNotFoundException | NumberFormatException | SQLException e){
                JOptionPane.showMessageDialog(null,e);

            }
            finally {

                try{
                    rs1.close();
                    rs.close();
                    pst.close();
                    pst1.close();

                }
                catch(SQLException e){
                    JOptionPane.showMessageDialog(null,e);

                }
            }
        }

    }//GEN-LAST:event_button_generateActionPerformed

